//! Shared RT-DETR helpers: request classification, run directory checking, and checkpoint lookup.

use std::path::{Path, PathBuf};

use crate::models::TrainingRequest;

/// Check if a training request is targeting an RT-DETR model.
pub(crate) fn is_rtdetr_request(request: &TrainingRequest) -> bool {
    if request.model_family.eq_ignore_ascii_case("RT-DETR")
        || request.model_family.eq_ignore_ascii_case("RTDETR")
    {
        return true;
    }
    let choice = request.model_choice.trim().to_ascii_lowercase();
    choice.contains("rtdetr") || choice.contains("rt-detr")
}

/// Check if a directory was generated by an RT-DETR training run.
pub(crate) fn is_rtdetr_run_dir(results_path: &Path) -> bool {
    let config_path = results_path.join("ls_trainer_config.json");
    if config_path.is_file() {
        if let Ok(text) = std::fs::read_to_string(&config_path) {
            if let Ok(json) = serde_json::from_str::<serde_json::Value>(&text) {
                if let Some(fam) = json.get("model_family").and_then(|v| v.as_str()) {
                    if fam.eq_ignore_ascii_case("RT-DETR") || fam.eq_ignore_ascii_case("RTDETR") {
                        return true;
                    }
                }
                if let Some(choice) = json.get("model_choice").and_then(|v| v.as_str()) {
                    if choice.to_ascii_lowercase().contains("rtdetr") {
                        return true;
                    }
                }
            }
        }
    }

    let training_cfg = results_path.join("training_config.json");
    if training_cfg.is_file() {
        if let Ok(text) = std::fs::read_to_string(&training_cfg) {
            if let Ok(json) = serde_json::from_str::<serde_json::Value>(&text) {
                if let Some(fam) = json.get("model_family").and_then(|v| v.as_str()) {
                    if fam.eq_ignore_ascii_case("RT-DETR") || fam.eq_ignore_ascii_case("RTDETR") {
                        return true;
                    }
                }
            }
        }
    }

    false
}

/// Locate an RT-DETR checkpoint within a results folder.
pub(crate) fn find_rtdetr_checkpoint_in_dir(results_path: &Path) -> Option<PathBuf> {
    if results_path.is_file() {
        let is_weight = results_path
            .extension()
            .map(|e| {
                let ext = e.to_string_lossy();
                ext.eq_ignore_ascii_case("pth") || ext.eq_ignore_ascii_case("pt")
            })
            .unwrap_or(false);
        if is_weight {
            let filename = results_path
                .file_name()
                .map(|f| f.to_string_lossy().to_ascii_lowercase())
                .unwrap_or_default();
            if filename.contains("rtdetr") {
                return Some(results_path.to_path_buf());
            }
            if let Some(parent) = results_path.parent() {
                if is_rtdetr_run_dir(parent) {
                    return Some(results_path.to_path_buf());
                }
            }
        }
    }

    if is_rtdetr_run_dir(results_path) {
        let candidates = [
            results_path.join("weights").join("best.pth"),
            results_path.join("best.pth"),
            results_path.join("weights").join("last.pth"),
            results_path.join("last.pth"),
            results_path.join("checkpoint.pth"),
        ];
        for c in candidates {
            if c.is_file() {
                return Some(c);
            }
        }
    }

    None
}

