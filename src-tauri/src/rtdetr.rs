//! Shared RT-DETR helpers: request classification, run directory checking, and checkpoint lookup.

use std::path::{Path, PathBuf};

use crate::models::TrainingRequest;

/// Resolve the HuggingFace pretrained model weights and friendly display name
/// based on the selected RT-DETR model ID or checkpoint path.
pub(crate) fn resolve_rtdetr_model_meta(model_choice: &str) -> (&'static str, &'static str) {
    let lower = model_choice.trim().to_ascii_lowercase();
    if lower.contains("rtdetr-x")
        || lower.contains("rtdetr_x")
        || lower.contains("-x.")
        || lower.ends_with("-x")
    {
        ("PekingU/rtdetr_v2_r101vd", "RT-DETR-X")
    } else if lower.contains("rtdetr-l")
        || lower.contains("rtdetr_l")
        || lower.contains("-l.")
        || lower.ends_with("-l")
    {
        ("PekingU/rtdetr_v2_r50vd", "RT-DETR-L")
    } else {
        ("PekingU/rtdetr_v2_r18vd", "RT-DETR v2-R18")
    }
}

/// Check if a training request is targeting an RT-DETR model.
/// A `best.pth` from an RT-DETR run counts even when the UI labeled it RF-DETR:
/// every `.pth` used to be treated as RF-DETR, and that loader expects `class_embed.bias`.
pub(crate) fn is_rtdetr_request(request: &TrainingRequest) -> bool {
    let choice_path = Path::new(request.model_choice.trim());
    if rtdetr_run_dir_for_checkpoint(choice_path).is_some() {
        return true;
    }
    if request.model_family.eq_ignore_ascii_case("RT-DETR")
        || request.model_family.eq_ignore_ascii_case("RTDETR")
    {
        return true;
    }
    let choice = request.model_choice.trim().to_ascii_lowercase();
    choice.contains("rtdetr") || choice.contains("rt-detr")
}

/// Run directory that produced `path`, when `path` is `best.pth` / `weights/best.pth`.
pub(crate) fn rtdetr_run_dir_for_checkpoint(path: &Path) -> Option<PathBuf> {
    if !path.is_file() {
        return None;
    }
    let parent = path.parent()?;
    if is_rtdetr_run_dir(parent) {
        return Some(parent.to_path_buf());
    }
    let in_weights = parent
        .file_name()
        .and_then(|name| name.to_str())
        .is_some_and(|name| name.eq_ignore_ascii_case("weights"));
    if in_weights {
        let run_dir = parent.parent()?;
        if is_rtdetr_run_dir(run_dir) {
            return Some(run_dir.to_path_buf());
        }
    }
    None
}

/// Hugging Face base and display name recorded by the run that wrote this checkpoint.
pub(crate) fn rtdetr_architecture_from_run(run_dir: &Path) -> Option<(String, String)> {
    if let Some(json) = read_json(&run_dir.join("training_config.json")) {
        let name = json
            .get("model_name")
            .and_then(|v| v.as_str())
            .unwrap_or("");
        if let Some(base) = json.get("base_weights").and_then(|v| v.as_str()) {
            if !base.is_empty() && !is_weight_file(base) {
                let label = if name.is_empty() {
                    resolve_rtdetr_model_meta(base).1.to_string()
                } else {
                    name.to_string()
                };
                return Some((base.to_string(), label));
            }
        }
        if !name.is_empty() {
            let (weights, label) = resolve_rtdetr_model_meta(name);
            return Some((weights.to_string(), label.to_string()));
        }
    }

    if let Some(json) = read_json(&run_dir.join("ls_trainer_config.json")) {
        let choice = json
            .get("model_choice")
            .and_then(|v| v.as_str())
            .unwrap_or("");
        let lower = choice.to_ascii_lowercase();
        if lower.contains("rtdetr") || lower.contains("rt-detr") {
            let (weights, label) = resolve_rtdetr_model_meta(choice);
            return Some((weights.to_string(), label.to_string()));
        }
    }

    None
}

fn read_json(path: &Path) -> Option<serde_json::Value> {
    let text = std::fs::read_to_string(path).ok()?;
    serde_json::from_str(&text).ok()
}

fn is_weight_file(value: &str) -> bool {
    let lower = value.to_ascii_lowercase();
    lower.ends_with(".pth") || lower.ends_with(".pt")
}

/// Check if a directory was generated by an RT-DETR training run.
pub(crate) fn is_rtdetr_run_dir(results_path: &Path) -> bool {
    let config_path = results_path.join("ls_trainer_config.json");
    if config_path.is_file() {
        if let Ok(text) = std::fs::read_to_string(&config_path) {
            if let Ok(json) = serde_json::from_str::<serde_json::Value>(&text) {
                if let Some(fam) = json.get("model_family").and_then(|v| v.as_str()) {
                    if fam.eq_ignore_ascii_case("RT-DETR") || fam.eq_ignore_ascii_case("RTDETR") {
                        return true;
                    }
                }
                if let Some(choice) = json.get("model_choice").and_then(|v| v.as_str()) {
                    if choice.to_ascii_lowercase().contains("rtdetr") {
                        return true;
                    }
                }
            }
        }
    }

    let training_cfg = results_path.join("training_config.json");
    if training_cfg.is_file() {
        if let Ok(text) = std::fs::read_to_string(&training_cfg) {
            if let Ok(json) = serde_json::from_str::<serde_json::Value>(&text) {
                if let Some(fam) = json.get("model_family").and_then(|v| v.as_str()) {
                    if fam.eq_ignore_ascii_case("RT-DETR") || fam.eq_ignore_ascii_case("RTDETR") {
                        return true;
                    }
                }
            }
        }
    }

    false
}

/// Locate an RT-DETR checkpoint within a results folder.
pub(crate) fn find_rtdetr_checkpoint_in_dir(results_path: &Path) -> Option<PathBuf> {
    if results_path.is_file() {
        let is_weight = results_path
            .extension()
            .map(|e| {
                let ext = e.to_string_lossy();
                ext.eq_ignore_ascii_case("pth") || ext.eq_ignore_ascii_case("pt")
            })
            .unwrap_or(false);
        if is_weight {
            let filename = results_path
                .file_name()
                .map(|f| f.to_string_lossy().to_ascii_lowercase())
                .unwrap_or_default();
            if filename.contains("rtdetr") {
                return Some(results_path.to_path_buf());
            }
            if let Some(parent) = results_path.parent() {
                if is_rtdetr_run_dir(parent) {
                    return Some(results_path.to_path_buf());
                }
            }
        }
    }

    if is_rtdetr_run_dir(results_path) {
        let candidates = [
            results_path.join("weights").join("best.pth"),
            results_path.join("best.pth"),
            results_path.join("weights").join("last.pth"),
            results_path.join("last.pth"),
            results_path.join("checkpoint.pth"),
        ];
        for c in candidates {
            if c.is_file() {
                return Some(c);
            }
        }
    }

    None
}
